import React from 'react';
import { AlertOctagon, ArrowUpRight, ShieldCheck, Zap } from 'lucide-react';
import { DashboardRiskData } from '../../types';

interface DynamicRiskSectionProps {
  risks: DashboardRiskData[];
  onNavigate: (pageId: string) => void;
  onSimulateEntity?: (entity: { id: string; name: string }) => void;
}

export const DynamicRiskSection: React.FC<DynamicRiskSectionProps> = ({
  risks,
  onNavigate,
  onSimulateEntity,
}) => {
  if (!risks || risks.length === 0) {
    return (
      <div className="p-8 rounded-2xl bg-slate-900/60 border border-slate-800 text-center space-y-3">
        <ShieldCheck className="w-10 h-10 text-emerald-400 mx-auto" />
        <h3 className="text-base font-semibold text-slate-200">No Critical Risks Detected</h3>
        <p className="text-xs text-slate-400 max-w-md mx-auto">
          All suppliers, warehouses, and SKU inventory buffers are operating within safe baseline parameters.
        </p>
      </div>
    );
  }

  const getSeverityBadge = (severity: string) => {
    switch (severity.toUpperCase()) {
      case 'CRITICAL':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-rose-500/10 text-rose-400 border border-rose-500/30 shadow-[0_0_12px_rgba(244,63,94,0.2)]">
            CRITICAL
          </span>
        );
      case 'HIGH':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-amber-500/10 text-amber-400 border border-amber-500/30">
            HIGH
          </span>
        );
      case 'MEDIUM':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-semibold bg-yellow-500/10 text-yellow-400 border border-yellow-500/30">
            MEDIUM
          </span>
        );
      default:
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-semibold bg-emerald-500/10 text-emerald-400 border border-emerald-500/30">
            LOW
          </span>
        );
    }
  };

  return (
    <div className="space-y-4">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h2 className="text-lg font-bold text-slate-100 flex items-center gap-2">
            <AlertOctagon className="w-5 h-5 text-rose-400" />
            Active Supply-Chain Vulnerabilities &amp; Risk Predictions
          </h2>
          <p className="text-xs text-slate-400 mt-0.5">
            Real-time inference generated by SynChain XGBoost risk prediction model with SHAP explainability
          </p>
        </div>

        <button
          onClick={() => onNavigate('risk')}
          className="inline-flex items-center gap-1.5 text-xs text-blue-400 hover:text-blue-300 font-medium transition-colors cursor-pointer self-start sm:self-auto"
        >
          View Full Risk Matrix
          <ArrowUpRight className="w-3.5 h-3.5" />
        </button>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
        {risks.slice(0, 6).map((risk) => {
          const scorePercent = risk.riskScore;
          const scoreColor =
            scorePercent > 80
              ? 'text-rose-400'
              : scorePercent > 60
              ? 'text-amber-400'
              : 'text-yellow-400';

          return (
            <div
              key={risk.id}
              className="p-5 rounded-2xl bg-slate-900/60 backdrop-blur-xl border border-slate-800/80 hover:border-slate-700/80 transition-all flex flex-col justify-between space-y-4 shadow-lg group hover:shadow-xl hover:shadow-blue-900/10"
            >
              <div>
                {/* Header: Score + Severity */}
                <div className="flex items-start justify-between gap-2">
                  <div>
                    <span className="text-[10px] text-slate-400 uppercase tracking-wider font-semibold block">
                      {risk.entityType.toUpperCase()} {risk.country ? `• ${risk.country}` : ''}
                    </span>
                    <h3 className="font-bold text-slate-100 text-sm tracking-tight mt-0.5 group-hover:text-blue-400 transition-colors">
                      {risk.entityName}
                    </h3>
                  </div>
                  <div className="text-right shrink-0">
                    <span className={`text-xl font-bold font-mono ${scoreColor}`}>{risk.riskScore}</span>
                    <span className="text-[10px] text-slate-400 block -mt-1">/100</span>
                  </div>
                </div>

                <div className="mt-2.5 flex items-center gap-2">
                  {getSeverityBadge(risk.severity)}
                  <span className="text-xs text-slate-400 truncate">{risk.category}</span>
                </div>

                {/* Analytical Explanation */}
                <p className="mt-3 text-xs text-slate-300/90 leading-relaxed line-clamp-3 bg-slate-950/40 p-3 rounded-xl border border-slate-850">
                  {risk.explanation}
                </p>

                {/* SHAP Contributing Factors */}
                {risk.contributingFactors && risk.contributingFactors.length > 0 && (
                  <div className="mt-3 space-y-1.5">
                    <span className="text-[10px] text-slate-400 uppercase font-semibold tracking-wider block">
                      Top Contributing Factors (SHAP)
                    </span>
                    <div className="flex flex-wrap gap-1.5">
                      {risk.contributingFactors.slice(0, 3).map((f, i) => (
                        <span
                          key={i}
                          className="px-2 py-0.5 rounded-md text-[10px] font-mono bg-slate-800 border border-slate-700/60 text-slate-300"
                        >
                          {f.feature.replace(/_/g, ' ')}: {f.score > 0 ? `+${f.score.toFixed(2)}` : f.score.toFixed(2)}
                        </span>
                      ))}
                    </div>
                  </div>
                )}
              </div>

              {/* Bottom Actions */}
              <div className="pt-3 border-t border-slate-800/60 flex items-center justify-between text-xs">
                {onSimulateEntity ? (
                  <button
                    onClick={() => onSimulateEntity({ id: risk.entityId, name: risk.entityName })}
                    className="inline-flex items-center gap-1.5 text-blue-400 hover:text-blue-300 font-medium transition-colors cursor-pointer"
                  >
                    <Zap className="w-3.5 h-3.5" />
                    Simulate Disruption
                  </button>
                ) : (
                  <button
                    onClick={() => onNavigate('scenario-builder')}
                    className="inline-flex items-center gap-1.5 text-blue-400 hover:text-blue-300 font-medium transition-colors cursor-pointer"
                  >
                    <Zap className="w-3.5 h-3.5" />
                    Simulate What-If
                  </button>
                )}

                <button
                  onClick={() => onNavigate('recommendations')}
                  className="inline-flex items-center gap-1 text-slate-400 hover:text-white transition-colors cursor-pointer"
                >
                  Playbook
                  <ArrowUpRight className="w-3 h-3" />
                </button>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
